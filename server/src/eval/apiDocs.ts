/**
 * CLI: `npm run docs:api`. Writes docs/api.md. Every example response is REAL output: the script seeds
 * nothing itself, it calls the running app code against the database named by MONGODB_URI (seeded
 * with `npm run seed`) and pastes what came back. Long arrays are abridged and say so.
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import request from 'supertest';
import { createApp } from '../app';
import { connectDb, disconnectDb } from '../config/db';
import { loadEnv } from '../config/env';
import { loadDotenv } from '../config/loadDotenv';
import { ids } from '../seed/ids';

const pid = (key: string) => ids.product(key).toHexString();
const json = (v: unknown) => JSON.stringify(v, null, 2);
const fence = (v: unknown) => '```json\n' + json(v) + '\n```';

/** Keeps the first `n` items of arrays under the listed keys and notes how many were cut. */
function abridge<T>(value: T, keys: string[], n: number): T {
  const walk = (v: unknown): unknown => {
    if (Array.isArray(v)) return v.map(walk);
    if (v && typeof v === 'object') {
      return Object.fromEntries(
        Object.entries(v).map(([k, val]) => {
          if (keys.includes(k) && Array.isArray(val) && val.length > n) {
            return [k, [...val.slice(0, n).map(walk), `... ${val.length - n} more not shown`]];
          }
          return [k, walk(val)];
        }),
      );
    }
    return v;
  };
  return walk(value) as T;
}

async function main(): Promise<void> {
  loadDotenv();
  const env = loadEnv();
  await connectDb(env.MONGODB_URI);
  const app = createApp(env, {
    rateLimits: {
      general: { windowMs: 60_000, limit: 1e9 },
      compare: { windowMs: 60_000, limit: 1e9 },
    },
  });
  const post = (b: unknown) =>
    request(app)
      .post('/api/v1/compare')
      .send(b as object);

  const basket2 = [
    { productId: pid('milk-tt-500'), quantity: 2 },
    { productId: pid('rice-1'), quantity: 1 },
    { productId: pid('dal-1'), quantity: 1 },
  ];
  const basketP = [
    { productId: pid('milk-tt-500'), quantity: 1 },
    { productId: pid('bun-4'), quantity: 1 },
    { productId: pid('rice-1'), quantity: 1 },
  ];

  const main = await post({ pinCode: '110002', items: basket2, sortBy: 'total' });
  const partial = await post({ pinCode: '110001', items: basketP, sortBy: 'total' });
  const unsupported = await post({ pinCode: '999999', items: basket2 });
  const invalid = await post({
    pinCode: '12345',
    items: [{ productId: 'nope', quantity: 0 }],
    sortBy: 'price',
  });
  const unknown = await post({
    pinCode: '110001',
    items: [{ productId: 'a'.repeat(24), quantity: 1 }],
  });
  const quoteId = main.body.results[0].quoteId as string;
  const quote = await request(app).get(`/api/v1/quotes/${quoteId}`);
  const missingQuote = await request(app).get(`/api/v1/quotes/${'b'.repeat(24)}`);

  const doc = `# API reference (Phase 3)

Base URL in development: \`http://localhost:4000/api/v1\`. All responses are JSON. Every error has the same shape:

${fence({ error: { code: 'VALIDATION_ERROR', message: 'Request validation failed', details: '(optional)' } })}

**Everything returned is sample data** for fictional providers. Any response that includes sample data says so (\`isSampleData\` and a \`DEMO_DATA\` warning), and the UI must show the Demo data banner.

_Generated by \`npm run docs:api\` from real responses of the running code. Long arrays are abridged where marked. The example ids are the deterministic seed ids._

## Status codes

| Code | Meaning |
| --- | --- |
| 200 | OK. A comparison can be 200 with empty \`results\` (unsupported PIN, nothing rankable); read \`warnings\`. |
| 400 | Validation failed (\`VALIDATION_ERROR\`, \`INVALID_JSON\`, \`UNKNOWN_PRODUCTS\`). \`details\` says which field. |
| 404 | Unknown route, or a quote id that does not exist (\`NOT_FOUND\`). |
| 413 | Request body over 100 kb (\`PAYLOAD_TOO_LARGE\`). |
| 429 | Rate limit hit (\`RATE_LIMITED\`), with a \`Retry-After\` header. Limits: 300 requests per minute per IP for the API, 60 per minute for \`POST /compare\`. |
| 502 | \`POST /compare\` only: every provider failed or timed out (\`PROVIDERS_UNAVAILABLE\`). If at least one provider answered, the response is 200 and the failures appear in \`unavailableProviders\` and \`warnings\`. |
| 500 | Unexpected error. No internals are returned. |

There are no 401/403 responses yet: the shopper API is public and the admin API arrives in Phase 6.

## POST /compare

Request body (unknown fields are rejected):

| Field | Type | Notes |
| --- | --- | --- |
| \`pinCode\` | string | 6 digits, not starting with 0. |
| \`items\` | array | 1 to 25 lines, each \`{ productId, quantity }\`. \`productId\` is a 24-character id from \`GET /products\`; a product may appear once; \`quantity\` is a whole number from 1 to 20. |
| \`sortBy\` | \`total\` \\| \`eta\` \\| \`balance\` | Default \`total\`. |
| \`mode\` | \`full-basket\` \\| \`partial\` | Default \`full-basket\`. |
| \`allowSubstitutes\` | boolean | Default \`false\`. Different-brand substitutes are used only if \`true\`. (Added to the spec so the opt-in rule in CLAUDE.md can be expressed.) |
| \`weights\` | \`{ priceWeight, timeWeight }\` | Only for \`balance\`. Each 0 to 1, must add up to 1. Default 0.5 / 0.5. |

How the response is organised:

- \`results\`: ranked providers, best first (ties share a rank). Each has \`estimatedTotal\`, \`etaMinutes\`, \`status\`, fees, coverage, lines and \`officialLink\`.
- \`partialResults\`: full-basket mode only. Providers missing items; not ranked; \`missingItems\` says which and why.
- \`unrankedResults\`: providers that cannot be ranked for this \`sortBy\`, with \`unrankedReason\` (\`NULL_TOTAL\` a fee is unknown, \`UNKNOWN_ETA\`, \`STALE_ETA\`, \`NO_ITEMS\`).
- \`unavailableProviders\`: no usable quote. \`reason\` is \`NOT_SERVING\` (explicitly does not deliver), \`NO_QUOTE\` (no data, which is not the same), \`TIMEOUT\`, \`ERROR\`, \`NOT_CONFIGURED\` or \`QUOTE_UNAVAILABLE\`.
- \`warnings\`: \`{ code, message, providerId? }\`, including \`DEMO_DATA\`, \`PIN_UNSUPPORTED\`, \`PIN_UNKNOWN\`, \`STALE_QUOTE\`, \`TOTAL_INCOMPLETE\`, \`MISSING_ITEMS\`, \`SUBSTITUTE_USED\`, \`PARTIAL_BASKET\`, \`PROVIDER_TIMEOUT\`, \`PROVIDER_ERROR\`.

An unknown value is \`null\`, never \`0\`: a fee that is not known is \`null\`, an unknown ETA is \`null\`, and a total that cannot be calculated is \`null\` with \`totalIncomplete: true\`.

### Example: PIN 110002, cheapest first (real output, abridged)

Request:

${fence({ pinCode: '110002', items: '(3 items: Milk 500 ml x2, Basmati Rice 1 kg, Toor Dal 1 kg)', sortBy: 'total' })}

Response (\`lines\` shortened; B is listed under \`unavailableProviders\` because it has no price data for this PIN):

${fence(abridge(main.body, ['lines', 'basket'], 1))}

### Example: full-basket mode with a missing item (real output, abridged)

Provider B does not list Pav Buns, so it appears under \`partialResults\` and is not ranked. C is complete but has an unknown platform fee, so it is under \`unrankedResults\` with a null total.

${fence(abridge(partial.body, ['lines', 'basket', 'appliedDiscounts', 'skippedDiscounts'], 1))}

### Example: an unsupported PIN (real output, abridged)

Status 200 with no rankings and a clear reason per provider:

${fence(abridge(unsupported.body, ['basket'], 1))}

### Example: validation errors (real output)

Status ${invalid.status}:

${fence(invalid.body)}

Status ${unknown.status} (well-formed id that is not in the catalogue):

${fence(unknown.body)}

## GET /quotes/:quoteId

Returns the stored price snapshot behind a result (\`quoteId\` in a provider result), including every listing, its match status, price and stock. Staleness is applied when it is read.

### Example (real output, \`items\` abridged)

Status ${quote.status}:

${fence(abridge(quote.body, ['items'], 2))}

Status ${missingQuote.status} for an id that does not exist:

${fence(missingQuote.body)}

## Other endpoints

\`GET /health\`, \`GET /locations/validate?pinCode=\`, \`GET /providers?pinCode=\` and \`GET /products?query&category&page&limit\` are described in the README (Phase 1).
`;

  writeFileSync(path.resolve(__dirname, '../../../docs/api.md'), doc, 'utf8');
  console.log(
    `wrote docs/api.md (compare ${main.status}, partial ${partial.status}, unsupported ${unsupported.status}, invalid ${invalid.status}, quote ${quote.status})`,
  );
}

main()
  .catch((err: unknown) => {
    console.error('docs:api failed:', err instanceof Error ? err.message : err);
    process.exitCode = 1;
  })
  .finally(() => disconnectDb());
